create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  role text not null default 'staff' check (role in ('admin','staff')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null,
  name text not null,
  created_at timestamptz not null default now(),
  unique(category, name)
);

create table if not exists public.waste (
  id bigint generated by default as identity primary key,
  staff_name text not null,
  category text not null,
  product text not null,
  amount double precision not null check (amount > 0),
  unit text not null,
  notes text not null default '',
  wasted_at timestamptz not null default now(),
  recorded_by text not null default ''
);

-- The Streamlit server accesses these tables using the Supabase service-role key.
-- Do not expose that key to browsers or commit it to source control.

-- Deny direct access through public/anon API roles. The server-side service role
-- used by Streamlit bypasses RLS; never expose that key to client code.
alter table public.users enable row level security;
alter table public.products enable row level security;
alter table public.waste enable row level security;
